// In-Memory state holder for local development
export class LocalDataStore {
  profiles: Map<string, UserProfile> = new Map([[DEMO_USER_ID, { ...initialProfile }]]);
  applications: Map<string, Application> = new Map(
    initialApplications.map((app) => [app.id, { ...app }])
  );
  interviews: Map<string, Interview> = new Map(
    initialInterviews.map((int) => [int.id, { ...int }])
  );
  recruiters: Map<string, Recruiter> = new Map(
    initialRecruiters.map((rec) => [rec.id, { ...rec }])
  );
  tasks: Map<string, Task> = new Map(initialTasks.map((t) => [t.id, { ...t }]));
  notes: Map<string, ApplicationNote> = new Map(
    initialNotes.map((n) => [n.id, { ...n }])
  );
  activity: ActivityLog[] = [...initialActivity];

  resetToDefault() {
    this.profiles = new Map([[DEMO_USER_ID, { ...initialProfile }]]);
    this.applications = new Map(
      initialApplications.map((app) => [app.id, { ...app }])
    );
    this.interviews = new Map(
      initialInterviews.map((int) => [int.id, { ...int }])
    );
    this.recruiters = new Map(
      initialRecruiters.map((rec) => [rec.id, { ...rec }])
    );
    this.tasks = new Map(initialTasks.map((t) => [t.id, { ...t }]));
    this.notes = new Map(initialNotes.map((n) => [n.id, { ...n }]));
    this.activity = [...initialActivity];
  }
}

